def main() -> None:
    out = Path("public/data/klimek-quizzes.json")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(bank, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    counts = [(qz["lectureId"], len(qz["questions"])) for qz in quizzes]
    print(f"Wrote {out} with {len(quizzes)} quizzes: {counts}")
