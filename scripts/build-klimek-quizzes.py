    assert all(n == 10 for _, n in counts)
    ids = [item["id"] for qz in quizzes for item in qz["questions"]]
    assert len(ids) == len(set(ids))
    for qz in quizzes:
        for item in qz["questions"]:
            assert item["answer"] in {o["key"] for o in item["options"]}
            assert len(item["options"]) == 4
            assert item["source"]["kind"] in {"open-rn", "original"}


